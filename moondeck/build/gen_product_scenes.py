#!/usr/bin/env python3
"""Generate the browser and firmware scene tables from the shared product catalog."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src/helio/scene-catalog.json"
EFFECT_CONTROLS = ("speed", "effect intensity", "custom 1", "custom 2", "custom 3",
                   "option 1", "option 2", "option 3")


def outputs():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    schema_paths = {"src/core/module/Control.h", "src/core/module/Control.cpp", "src/light/drivers/Drivers.h",
                    "src/light/effects/EffectBase.h", "src/light/util/Palette.h", "src/helio/BleSceneCatalog.h"}
    for scene in data["extraScenes"] + data["factoryScenes"]:
        name = "HelioWledPresetsEffect" if scene["type"].startswith("Helio") else scene["type"]
        schema_paths.add(f"src/light/effects/{name}.h")
    digest = hashlib.sha256(json.dumps(data, sort_keys=True, separators=(",", ":")).encode())
    for relative in sorted(schema_paths):
        digest.update(relative.encode())
        digest.update((ROOT / relative).read_bytes())
    revision = digest.hexdigest()[:12]
    factory = data["factoryScenes"]
    scenes = data["extraScenes"] + factory
    rows = []
    for scene in scenes:
        controls = dict(scene["controls"])
        global_palette = scene.get("usesGlobalPalette", "palette" not in controls and scene["type"] != "SolidEffect")
        if global_palette:
            controls["palette"] = scene["palette"]
        values = [scene["id"], scene["label"], scene["type"], json.dumps(controls, separators=(",", ":"))]
        literals = ", ".join(json.dumps(value, ensure_ascii=True) for value in values)
        rows.append("    {" + literals + ", " + str(scene.get("audio", False)).lower() + ", " + str(global_palette).lower() + "},")
    header = """#pragma once

/// Generated by moondeck/build/gen_product_scenes.py from scene-catalog.json.
namespace mm::product_scenes {
struct Entry { const char* id; const char* name; const char* type; const char* controls; bool audio; bool globalPalette; };
"""
    header += f'inline constexpr const char* kRevision = "{revision}";\n'
    header += "inline constexpr Entry kEntries[] = {\n" + "\n".join(rows) + "\n};\n"
    visibility = []
    for scene in factory:
        if "presetIndex" not in scene or "controlMetadata" not in scene:
            continue
        metadata = scene.get("controlMetadata", {})
        mask = sum(1 << bit for bit, name in enumerate(EFFECT_CONTROLS)
                   if metadata.get(name, {}).get("portVisible", metadata.get(name, {}).get("visible", False)))
        visibility.append(f"    {{{scene['presetIndex']}, {mask}}},")
    header += "inline constexpr const char* kEffectControls[] = {" + ", ".join(json.dumps(name) for name in EFFECT_CONTROLS) + "};\n"
    header += "struct ControlVisibility { unsigned char preset; unsigned char mask; };\n"
    header += "inline constexpr ControlVisibility kControlVisibility[] = {\n" + "\n".join(visibility) + "\n};\n}\n"
    browser = "// Generated by moondeck/build/gen_product_scenes.py from the shared product catalog.\n"
    browser += "export const HELIO_FACTORY_SCENES = " + json.dumps(factory, ensure_ascii=False, separators=(",", ":")) + ";\n"
    return {ROOT / "src/helio/BleSceneData.h": header, ROOT / "src/ui/helio-scene-data.js": browser}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if either generated table differs")
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        raise SystemExit("Regenerate product scenes: " + ", ".join(stale))
    print("Product scene tables current" if args.check else "Generated product scene tables")


if __name__ == "__main__":
    main()
