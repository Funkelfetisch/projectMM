#!/usr/bin/env python3
"""Generate the product setup choices, for the dashboard and for the firmware's BLE setup, from the device-model catalogue."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "mooninstaller/deviceModels.json"
OUTPUT = ROOT / "src/ui/nebulite-profile-data.js"
HEADER = ROOT / "src/helio/ProductProfiles.h"


def profiles():
    profiles = []
    for model in json.loads(CATALOG.read_text(encoding="utf-8")):
        if not {"nebulite-s3", "nebulite-esp32"}.intersection(model["firmwares"]):
            continue
        state = model["state"]
        profiles.append({
            "name": model["name"], "displayName": model.get("displayName", model["name"]), "chip": model["chip"],
            "firmwares": model["firmwares"],
            "description": model.get("description", ""),
            "state": {key: state[key] for key in ("System", "Drivers", "Layouts")},
        })
    return profiles


def output():
    return ("// Generated by moondeck/build/gen_product_profiles.py from deviceModels.json.\n"
            "export const NEBULITE_SETUP_PROFILES = "
            + json.dumps(profiles(), ensure_ascii=True, separators=(",", ":")) + ";\n")


def header():
    rows = []
    for profile in profiles():
        values = [profile["name"], ",".join(profile["firmwares"]), profile["chip"],
                  json.dumps(profile["state"], ensure_ascii=True, separators=(",", ":"))]
        rows.append("    {" + ", ".join(json.dumps(value, ensure_ascii=True) for value in values) + "},")
    return ("#pragma once\n\n"
            "/// Generated by moondeck/build/gen_product_profiles.py from mooninstaller/deviceModels.json.\n"
            "namespace mm::product_profiles {\n"
            "/// A setup choice: the firmwares (comma-separated) and chip it fits, and the System/Drivers/Layouts document it applies.\n"
            "struct Entry { const char* name; const char* firmwares; const char* chip; const char* state; };\n"
            "inline constexpr Entry kEntries[] = {\n" + "\n".join(rows) + "\n};\n"
            "}  // namespace mm::product_profiles\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in ((OUTPUT, output()), (HEADER, header())):
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                parser.exit(1, "Product setup catalogue is stale: run uv run moondeck/build/gen_product_profiles.py\n")
        else:
            path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
